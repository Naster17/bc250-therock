#!/usr/bin/env python3
"""Create an additive two-host entry point for the audited lora-smoke script."""
import argparse
import hashlib
from pathlib import Path

SOURCE = "0173cb5ea68d8aeefed52c2e00c0a4f041e08624714dbdc25bb1c52a68dad2ca"


def prepare(source: Path, destination: Path) -> None:
    original = source.read_bytes()
    if hashlib.sha256(original).hexdigest() != SOURCE:
        raise ValueError("Application source changed; review before regenerating")
    text = original.decode()

    def replace(old, new):
        nonlocal text
        if text.count(old) != 1:
            raise ValueError(f"Expected one integration point: {old!r}")
        text = text.replace(old, new)

    replace(
        "    args = parse_args()\n",
        "    args = parse_args()\n    from bc250_lora_support import configure, Audit\n    benchmark = configure(args)\n",
    )
    replace(
        "            callbacks=[DetailedMetrics(args.output_dir)],",
        "            callbacks=[DetailedMetrics(args.output_dir), Audit(args.output_dir)],",
    )
    replace(
        "            push_to_hub=False,",
        "            push_to_hub=False,\n            ddp_find_unused_parameters=True,\n            ddp_broadcast_buffers=False,\n            average_tokens_across_devices=True,",
    )
    replace(
        "        trained = sum(",
        "        from bc250_lora_support import configure_trainer\n        configure_trainer(trainer)\n        trained = sum(",
    )
    replace(
        '        LOG.info("Training result: %s", result.metrics)',
        '        LOG.info("Training result: %s", result.metrics)\n        if benchmark:\n            return 0',
    )
    replace(
        "        trainer.save_model(str(final_dir))",
        "        trainer.save_model(str(final_dir))\n        if is_main:\n            from bc250_lora_support import verify_saved_adapter\n            verify_saved_adapter(trainer, final_dir)",
    )
    replace(
        "        return 1\n\n\nif __name__",
        "        return 1\n    finally:\n        from bc250_lora_support import cleanup\n        cleanup()\n\n\nif __name__",
    )
    replace(
        "        if trainer.is_world_process_zero():\n            tokenizer.save_pretrained(str(final_dir))",
        '        if eval_dataset is not None:\n            # Evaluation contains collectives; every rank must enter it.\n            ev = trainer.evaluate()\n            if trainer.is_world_process_zero():\n                trainer.save_metrics("eval", ev)\n        if trainer.is_world_process_zero():\n            tokenizer.save_pretrained(str(final_dir))',
    )
    start = text.index(
        "            if eval_dataset is not None:\n                LOG.info("
    )
    stop = text.index('            LOG.info("ADAPTER SAVED:', start)
    text = text[:start] + text[stop:]
    banner = "# Generated by the source-pinned BC-250 LoRA integration; original train.py preserved.\n"
    output = (banner + text).encode()
    if destination.exists() and destination.read_bytes() != output:
        previous = destination.read_bytes()
        digest = hashlib.sha256(previous).hexdigest()
        if digest != "46da42893ae526471659dfe8b9d3fadc1dd09fa5454070082156a4c9f5ee434e":
            raise FileExistsError(destination)
        backup = destination.with_name(destination.stem + "." + digest[:12] + ".py")
        if backup.exists() and backup.read_bytes() != previous:
            raise FileExistsError(backup)
        backup.write_bytes(previous)
    destination.write_bytes(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    prepare(args.source, args.destination)
